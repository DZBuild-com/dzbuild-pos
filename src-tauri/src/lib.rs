/// Every command and event, exported to `src/bindings.ts`. Errors are thrown as `{ code, … }`
/// objects. Only the bindings export builds it (NFR-002): the app takes its commands through
/// `tauri::generate_handler` ([`run`]), without their type descriptions.
pub fn specta_builder() -> Builder<tauri::Wry> {
    builder_with_events()
        // The value of the `documents.texts` setting (and its `Trilingual`, also the value of
        // `company.activity`): read and written as JSON by `settings_get`/`settings_set`.
        .typ::<pos_core::billing::settings::DocumentTexts>()
        .commands(app_commands!(collect_commands))
}

/// Writes `path` (`src/bindings.ts`) and, beside it, `bindings-packs.ts`: the pack commands'
/// bindings, out of the till's first chunk ([`bindings_split`]).
pub fn export_bindings(
    builder: &Builder<tauri::Wry>,
    path: impl AsRef<Path>,
) -> Result<(), String> {
    let path = path.as_ref();
    builder
        .export(Typescript::default().header(BINDINGS_HEADER), path)
        .map_err(|e| e.to_string())?;
    let full = std::fs::read_to_string(path).map_err(|e| e.to_string())?;
    let (core, packs) =
        bindings_split::split(&full, BINDINGS_HEADER, bindings_split::PACK_BINDINGS)?;
    std::fs::write(path, core).map_err(|e| e.to_string())?;
    std::fs::write(path.with_file_name(PACK_BINDINGS_FILE), packs).map_err(|e| e.to_string())
}

/// The pack commands' bindings, beside `src/bindings.ts`.
pub const PACK_BINDINGS_FILE: &str = "bindings-packs.ts";

/// `common:nativeFatal` of the three locales, for the one message Windows shows by itself when
/// Tauri cannot start (no window, no webview, so no i18next): Arabic, French and English at
/// once, then `detail`. Returns `(title, body)`.
pub(crate) fn native_fatal_text(detail: &str) -> (String, String) {
    use pos_core::lang::Lang;
    let title = texts::catalogue_text(Lang::Fr, &["appName"]).unwrap_or_default();
    let mut paragraphs: Vec<String> = [Lang::Ar, Lang::Fr, Lang::En]
        .into_iter()
        .filter_map(|lang| texts::catalogue_text(lang, &["nativeFatal", "body"]))
        .collect();
    paragraphs.push(detail.to_owned());
    (title, paragraphs.join("\n\n"))
}

/// Tauri could not build the app: tell the user in a native message box (a release build has
/// no console), then exit.
fn exit_with_native_message(detail: &str) -> ! {
    eprintln!("DZBuild POS failed to start: {detail}");
    tracing::error!(detail, "DZBuild POS failed to start");
    let (title, body) = native_fatal_text(detail);
    #[cfg(windows)]
    {
        rfd::MessageDialog::new()
            .set_level(rfd::MessageLevel::Error)
            .set_title(title)
            .set_description(body)
            .set_buttons(rfd::MessageButtons::Ok)
            .show();
    }
    #[cfg(not(windows))]
    eprintln!("{title}: {body}");
    std::process::exit(1)
}

/// `tauri::generate_handler!`'s closure, typed so that it can wait in a variable for the licence
/// gate (Tauri infers its argument only where `invoke_handler` takes it directly).
fn tauri_handler<F>(handler: F) -> F
where
    F: Fn(tauri::ipc::Invoke<tauri::Wry>) -> bool + Send + Sync + 'static,
{
    handler
}

pub fn run() {
    STARTED.get_or_init(std::time::Instant::now);
    // First thing: a panic anywhere from here on (window, WebView2, setup) leaves `crash.log`.
    logging::install_crash_hook(&logging::default_crash_dir());
    #[cfg(debug_assertions)]
    if let Err(error) = export_bindings(&specta_builder(), "../src/bindings.ts") {
        eprintln!("could not export src/bindings.ts: {error}");
    }
    // NFR-002: the app never builds the bindings' type descriptions (about 4 MB of release code,
    // and their work at every start); it mounts the events and takes the same command list
    // through Tauri's own handler (`contract_tests::the_app_runs_without_the_bindings_type_descriptions`).
    let events = builder_with_events();
    // M9: every command goes through the licence gate first (default deny in read-only
    // mode); Tauri's handler runs the ones it lets through. This file holds one handler call,
    // Tauri's gated one (`contract_tests::every_command_goes_through_the_licence_gate`).
    let commands = tauri_handler(app_commands!(tauri::generate_handler));
    let app = tauri::Builder::default()
        // single-instance must be registered first
        .plugin(tauri_plugin_single_instance::init(|app, _argv, _cwd| {
            if let Some(window) = app.get_webview_window("main") {
                let _ = window.unminimize();
                let _ = window.show();
                let _ = window.set_focus();
            }
        }))
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_os::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_fs::init())
        // Signed updates; the webview has no updater permission (`commands::updates` only).
        .plugin(tauri_plugin_updater::Builder::new().build())
        .invoke_handler(move |invoke| license::handle(invoke, &commands))
        // The customer screen has no close button and would keep the app (its database and
        // serial ports) alive: the app ends with the till's window (`on_exit` runs). A
        // minimised till window trims WebView2's memory (NFR-004). Closing the till's window
        // asks first on a main PC with tills online (LAN-003), then backs up when it is due
        // (DAT-024): both in `closing`.
        .on_window_event(|window, event| {
            if window.label() == "main" && matches!(event, tauri::WindowEvent::Destroyed) {
                window.app_handle().exit(0);
            }
            webview::on_window_event(window, event);
            if let tauri::WindowEvent::CloseRequested { api, .. } = event {
                closing::on_close_requested(window, api);
            }
        })
        .setup(move |app| {
            events.mount_events(app);
            // The fatal screen's guided restore maps its ids to paths here (`commands::recovery`).
            app.manage(commands::recovery::RecoveryCatalog::default());
            if let Some(window) = app.get_webview_window("main") {
                webview::disable_browser_accelerators(&window);
            }
            let channel = std::sync::Arc::new(print_host::HostChannel::new());
            let surface = std::sync::Arc::new(print_host::WebviewSurface::new(
                app.handle().clone(),
                channel.clone(),
            ));
            let host = std::sync::Arc::new(print_host::PrintHost::new(surface, channel));
            host.start_idle_closer();
            app.manage(host);
            // The updater service before the database opens: `updates_status` answers from the
            // first screen; the checker starts in `state::on_ready`.
            let updater = app.config().plugins.0.get("updater").cloned();
            let configured = updater
                .as_ref()
                .and_then(|u| u.get("endpoints"))
                .and_then(|e| e.get(0))
                .and_then(|e| e.as_str())
                .unwrap_or("https://dzbuild.com/pos/updates/stable/latest.json")
                .to_owned();
            // A till checks the setup its main PC mirrors with the plugin's public key.
            let pubkey = updater
                .as_ref()
                .and_then(|u| u.get("pubkey"))
                .and_then(|k| k.as_str())
                .unwrap_or_default()
                .to_owned();
            app.manage(std::sync::Arc::new(updates::UpdateService::new(
                std::sync::Arc::new(updates::ShopSource::new(app.handle().clone(), pubkey)),
                configured,
            )));
            state::setup(app)
        })
        .build(tauri::generate_context!());
    match app {
        Ok(app) => app.run(|handle, event| match event {
            tauri::RunEvent::Ready => state::on_ready(handle),
            tauri::RunEvent::Exit => state::on_exit(handle),
            // The hidden print window must not keep the app running once the main one is gone.
            tauri::RunEvent::WindowEvent {
                label,
                event: tauri::WindowEvent::Destroyed,
                ..
            } if label == "main" => {
                if let Some(host) = handle.get_webview_window(print_host::PRINT_HOST) {
                    let _ = host.close();
                }
            }
            _ => {}
        }),
        Err(error) => exit_with_native_message(&error.to_string()),
    }
}
